HttpClient createPinnedHttpClient() {
  final context = SecurityContext(withTrustedRoots: false)
    ..setTrustedCertificatesBytes(utf8.encode(_isrgRootX1))
    ..setTrustedCertificatesBytes(utf8.encode(_isrgRootX2));
  final client = HttpClient(context: context)
    ..connectionTimeout = AppConfig.connectTimeout
    ..idleTimeout = const Duration(seconds: 30)
    ..maxConnectionsPerHost = 6
    ..autoUncompress = true
    ..userAgent = 'Ketoshop-Android/${AppConfig.appVersion}';
  // A certificate that does not chain to the roots above is never accepted,
  // whatever the reason. No system or environment proxy either.
  client.badCertificateCallback = (cert, host, port) => false;
  client.findProxy = (uri) => 'DIRECT';
  return client;
}
