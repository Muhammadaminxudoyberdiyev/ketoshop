"""Generate the app's string tables from mobile/l10n/{uz,ru}.json.

uz_cyr (Cyrillic) and uz_new (the 2026 Latin: ö ğ ş ç) are not written by
hand: they come from the server's own translit.py, so the app spells words
exactly like the bot and the Mini App do. Also writes test vectors so the
Dart port of to_new_latin (lib/core/l10n/alphabet.dart) is checked against
the Python original.

    python mobile/tool/gen_l10n.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

MOBILE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(MOBILE.parent))

import translit  # noqa: E402  (the repo root's module)

ALPHABET_SAMPLES = [
    "Bodom uni 500 g", "Shokoladli pechenye", "O'simlik yog'i", "Choy", "G'o'za",
    "SHAKAR O'RNINI BOSUVCHI", "Sh", "Is'hoq", "'Kakao' kukuni", "Keto shop sovg'asi",
    "Ketoshop", "https://t.me/ketoshop_uz", "@keto_market bilan bog'laning",
    "{n} ta mahsulot", "Chegirma: o‘zgarmas", "To'g`ri", "Choyshab va sharbat",
    "Kokos shakari (1 kg)", "Ch", "Ishonch", "Mosh", "Eritritol", "charged",
    "Oʻzbekiston", "Asal, yong'oq va shokolad", "100 g da 4 g uglevod",
]


def dart_string(value: str) -> str:
    escaped = (value.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")
               .replace("\n", "\\n").replace("\r", ""))
    return f"'{escaped}'"


def dart_map(entries: dict[str, str], indent: str = "    ") -> str:
    return "\n".join(f"{indent}{dart_string(k)}: {dart_string(v)}," for k, v in entries.items())


def main() -> None:
    uz = json.loads((MOBILE / "l10n" / "uz.json").read_text(encoding="utf-8"))
    ru = json.loads((MOBILE / "l10n" / "ru.json").read_text(encoding="utf-8"))
    missing = sorted(set(uz) ^ set(ru))
    if missing:
        raise SystemExit(f"uz.json and ru.json differ in keys: {missing}")
    tables = {
        "uz": uz,
        "uz_new": {k: translit.to_new_latin(v) for k, v in uz.items()},
        "uz_cyr": {k: translit.lat_to_cyr(v) for k, v in uz.items()},
        "ru": ru,
    }
    body = "\n".join(f"  '{name}': {{\n{dart_map(table)}\n  }}," for name, table in tables.items())
    out = MOBILE / "lib" / "core" / "l10n" / "strings.g.dart"
    out.write_text(
        "// GENERATED by tool/gen_l10n.py from l10n/uz.json and l10n/ru.json — do not edit.\n"
        "// uz_new and uz_cyr come from the server's translit.py.\n\n"
        f"const Map<String, Map<String, String>> kStrings = {{\n{body}\n}};\n",
        encoding="utf-8", newline="\n")

    vectors = "\n".join(f"  ({dart_string(s)}, {dart_string(translit.to_new_latin(s))}),"
                        for s in ALPHABET_SAMPLES)
    (MOBILE / "test" / "alphabet_vectors.g.dart").write_text(
        "// GENERATED by tool/gen_l10n.py: translit.to_new_latin(input) on the server.\n\n"
        f"const List<(String, String)> kAlphabetVectors = [\n{vectors}\n];\n",
        encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(MOBILE)} ({len(uz)} keys) and test/alphabet_vectors.g.dart")


if __name__ == "__main__":
    main()
